"""Shared ReportLab building blocks for school documents."""

from __future__ import annotations

import io
from collections.abc import Callable
from typing import Any

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

BRAND = colors.HexColor("#0f6b4f")
GRID = colors.HexColor("#c8d1cd")

styles = getSampleStyleSheet()
TITLE = ParagraphStyle("title", parent=styles["Title"], fontSize=16, spaceAfter=2, textColor=BRAND)
SUB = ParagraphStyle("sub", parent=styles["Normal"], fontSize=9, alignment=1, textColor=colors.grey)
H = ParagraphStyle("h", parent=styles["Heading3"], fontSize=11, spaceBefore=6, spaceAfter=4)
BODY = ParagraphStyle("body", parent=styles["Normal"], fontSize=9, leading=12)
SMALL = ParagraphStyle("small", parent=styles["Normal"], fontSize=7.5, textColor=colors.grey)


def header(profile: Any, document_title: str) -> list[Any]:
    lines = [Paragraph(profile.name, TITLE)]
    detail = " · ".join(
        p for p in (profile.motto, profile.address, profile.phone, profile.email) if p
    )
    if detail:
        lines.append(Paragraph(detail, SUB))
    lines += [Spacer(1, 3 * mm), Paragraph(document_title, H)]
    return lines


def table(
    rows: list[list[Any]],
    widths: list[float],
    *,
    header_row: bool = True,
    align_right_from: int | None = None,
) -> Table:
    t = Table(rows, colWidths=widths, repeatRows=1 if header_row else 0)
    style = [
        ("FONTSIZE", (0, 0), (-1, -1), 8.5),
        ("GRID", (0, 0), (-1, -1), 0.4, GRID),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 3),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
    ]
    if header_row:
        style += [
            ("BACKGROUND", (0, 0), (-1, 0), BRAND),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ]
    if align_right_from is not None:
        style.append(("ALIGN", (align_right_from, 0), (-1, -1), "RIGHT"))
    t.setStyle(TableStyle(style))
    return t


def key_values(pairs: list[tuple[str, str]], width: float) -> Table:
    rows = []
    for i in range(0, len(pairs), 2):
        chunk = pairs[i : i + 2]
        row: list[Any] = []
        for label, value in chunk:
            row += [Paragraph(f"<b>{label}</b>", BODY), Paragraph(value or "—", BODY)]
        while len(row) < 4:
            row.append("")
        rows.append(row)
    return table(rows, [width * 0.18, width * 0.32, width * 0.18, width * 0.32], header_row=False)


def render(build: Callable[[float], list[Any]], *, title: str, footer: str = "") -> bytes:
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=14 * mm,
        rightMargin=14 * mm,
        topMargin=12 * mm,
        bottomMargin=14 * mm,
        title=title,
        author="Nex Edu",
    )

    def on_page(canvas: Any, _doc: Any) -> None:
        canvas.saveState()
        canvas.setFont("Helvetica", 7)
        canvas.setFillColor(colors.grey)
        text = f"{footer}   Generated by Nex Edu" if footer else "Generated by Nex Edu"
        canvas.drawString(14 * mm, 8 * mm, text)
        canvas.restoreState()

    doc.build(build(doc.width), onFirstPage=on_page, onLaterPages=on_page)
    return buffer.getvalue()
